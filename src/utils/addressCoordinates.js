export const getAddressDistrict = (address) => {
  const tokens = String(address ?? '').trim().split(/\s+/).filter(Boolean);
  return (
    tokens.find((token) => /[가-힣]+구$/.test(token)) ||
    tokens.find((token) => /[가-힣]+(?:시|군)$/.test(token)) ||
    ''
  );
};

export const getAddressCoordinate = (address) => {
  const normalized = String(address ?? '').replace(/\s+/g, '');
  if (!normalized) {
    return null;
  }

  const exactMatch = ADDRESS_COORDINATE_RULES.find((rule) =>
    rule.terms.every((term) => normalized.includes(term.replace(/\s+/g, '')))
  );
  if (exactMatch) {
    return exactMatch.coordinate;
  }

  const district = getAddressDistrict(address);
  const districtMatches = ADDRESS_COORDINATE_RULES.filter((rule) => rule.district === district);
  return districtMatches.length === 1 ? districtMatches[0].coordinate : null;
};
